-- The test domain's table (test/support/domain.ts): one row per page a crawl
-- scraped, beside the core's url row for it. Loaded after etc/schema.sql.

DROP TABLE IF EXISTS page CASCADE;

CREATE TABLE page (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    url_id              bigint NOT NULL UNIQUE REFERENCES url(id) ON DELETE CASCADE,
    title               text NOT NULL,
    body                text,
    status              text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'gone'))
);
