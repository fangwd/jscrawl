-- jscrawl: generic web product crawler (PostgreSQL)

DROP TABLE IF EXISTS
    crawler_run, crawl_snapshot, issue,
    variant_price, product_image_variant, product_variant_value, product_variant,
    product_attribute_value, product_attribute, product_attribute_group,
    product_asset, product_image, product_category, product_url, product,
    brand, category,
    url_graph, url_fetch, url, site, crawler
    CASCADE;

-- ============================================================================
-- 1. Crawl infrastructure
-- ============================================================================

CREATE TABLE crawler (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL UNIQUE,
    wait_time           integer NOT NULL DEFAULT 0,      -- seconds between requests
    random_wait         integer NOT NULL DEFAULT 0,      -- extra random seconds
    thread_count        integer NOT NULL DEFAULT 1,
    max_retry_count     integer NOT NULL DEFAULT 5,
    proxy_type          text,
    use_puppeteer       boolean NOT NULL DEFAULT false,
    page_snapshots      text NOT NULL DEFAULT 'gzip'
                        CHECK (page_snapshots IN ('gzip', 'raw', 'off')),
    allow               jsonb NOT NULL DEFAULT '[]',     -- url path rules, robots.txt syntax
    disallow            jsonb NOT NULL DEFAULT '[]',
    refresh_minutes     integer CHECK (refresh_minutes > 0) -- re-crawl this long after the last crawl started; null: never
);

-- A crawled website. One site sells in one currency; a multi-region shop is
-- one site per region.
CREATE TABLE site (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crawler_id          integer REFERENCES crawler(id),
    name                text NOT NULL UNIQUE,
    currency            char(3),                         -- ISO 4217
    locale              text,                            -- BCP-47
    scope               text,                            -- the part of the catalogue the crawl keeps to; null for all of it
    expect              jsonb                            -- what a finished crawl must hold (see src/core/expect.ts); null: unchecked
);

CREATE TABLE url (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer REFERENCES site(id),
    type                text NOT NULL,                   -- seed, category, product, image, asset...
    data                text,
    priority            integer NOT NULL DEFAULT 0,
    url                 text NOT NULL,
    hash                char(40) NOT NULL UNIQUE,        -- sha1(url)
    version             integer NOT NULL DEFAULT 0,
    visit_time          timestamptz,
    status              smallint NOT NULL DEFAULT 0,     -- 0 idle, 1 busy, 2 done, 3 disallowed, <0 failed
    claimed_at          timestamptz                      -- when it went busy; stale claims are reclaimed
);

CREATE INDEX idx_url_claim ON url (site_id, status, type, priority DESC);

CREATE TABLE url_fetch (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    fetch_time          timestamptz NOT NULL,
    fetch_duration      real,
    http_status         integer,                         -- NULL when no response arrived
    final_url           text,                            -- after redirects
    error               text,                            -- transport error, e.g. ETIMEDOUT
    content_type        text,
    content_hash        char(32),
    content_length      integer NOT NULL DEFAULT 0,
    UNIQUE (url_id, fetch_time)
);

-- Link graph: src page links to dst.
CREATE TABLE url_graph (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    dst_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    UNIQUE (src_id, dst_id)
);

CREATE INDEX idx_url_graph_dst ON url_graph (dst_id);

-- A problem surfaced by a crawl: a scrape that threw, or scraped data that
-- failed validation. One unsettled (open or triaged) issue per (url, kind): a
-- page failing again while its issue awaits review is the same issue.
CREATE TABLE issue (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    kind                text NOT NULL,                   -- scrape_failed, validation
    detail              text NOT NULL,
    status              text NOT NULL DEFAULT 'open'
                        CHECK (status IN ('open', 'triaged', 'resolved', 'ignored')),
    verdict             text,                            -- agent's classification: correct, stale, extractor_bug...
    resolution          text,                            -- agent's findings + proposed fix (never applied here)
    same_as             bigint REFERENCES issue(id) ON DELETE SET NULL, -- the issue whose verdict this one took; its status follows
    created_at          timestamptz NOT NULL DEFAULT now(),
    resolved_at         timestamptz
);

CREATE UNIQUE INDEX uq_issue_unsettled ON issue (url_id, kind) WHERE status IN ('open', 'triaged');
CREATE INDEX idx_issue_status ON issue (status);
CREATE INDEX idx_issue_same_as ON issue (same_as);

-- A site's state at the end of each complete crawl (src/core/snapshot.ts): the
-- next one is compared with it, and a regression becomes an issue.
CREATE TABLE crawl_snapshot (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    taken_at            timestamptz NOT NULL DEFAULT now(),
    products            integer NOT NULL,                -- active, with a variant
    fields              jsonb NOT NULL,                  -- products carrying each field: {price: n, ...}
    pages               jsonb NOT NULL                   -- product pages: {done: n, failed: n}
);

CREATE INDEX idx_crawl_snapshot_site ON crawl_snapshot (site_id, taken_at DESC);

-- Crawler processes managed by the supervisor (src/core/supervisor.ts):
-- one row per spawned crawl or one-shot scrape.
CREATE TABLE crawler_run (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id     integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    kind        text NOT NULL DEFAULT 'crawl',           -- crawl, oneshot
    pid         integer,
    -- stopped: finished, or asked to stop (Ctrl+C, the stop button, a server
    -- shutdown); blocked: stopped itself as the site refused its fetches;
    -- crashed: failed on its own; interrupted: the server died first
    status      text NOT NULL DEFAULT 'running'
                CHECK (status IN ('running', 'stopped', 'blocked', 'crashed', 'interrupted')),
    started_at  timestamptz NOT NULL DEFAULT now(),
    stopped_at  timestamptz,
    exit_code   integer,
    log_path    text
);

CREATE INDEX idx_crawler_run_site ON crawler_run (site_id, started_at DESC);

-- ============================================================================
-- 2. Catalogue
-- ============================================================================

CREATE TABLE category (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    parent_id           integer REFERENCES category(id) ON DELETE CASCADE, -- NULL = top level
    url_id              bigint NOT NULL UNIQUE REFERENCES url(id) ON DELETE CASCADE, -- a category is identified by its page
    name                text NOT NULL,
    description         text,
    image_id            bigint REFERENCES url(id) ON DELETE SET NULL, -- the category's picture
    sort_order          integer NOT NULL DEFAULT 0
);

CREATE INDEX idx_category_parent ON category (parent_id);

CREATE TABLE brand (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL UNIQUE,
    logo_url_id         bigint REFERENCES url(id) ON DELETE SET NULL
);

-- Every product has at least one variant; simple products carry a single
-- default variant (code = '') that holds the price.
CREATE TABLE product (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    brand_id            integer REFERENCES brand(id) ON DELETE SET NULL,

    code                text NOT NULL,                   -- site's stable product id
    name                text,
    short_description   text,
    description         text,

    status              text NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'gone')), -- gone = no longer on the site

    rating_value        numeric(4,2),
    review_count        integer,

    structured_data     jsonb,                           -- JSON-LD / embedded state as extracted

    first_seen_at       timestamptz NOT NULL DEFAULT now(),
    last_seen_at        timestamptz NOT NULL DEFAULT now(),

    UNIQUE (site_id, code)
);

CREATE INDEX idx_product_brand ON product (brand_id);

CREATE TABLE product_url (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    url_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    UNIQUE (product_id, url_id)
);

CREATE TABLE product_category (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    category_id         integer NOT NULL REFERENCES category(id) ON DELETE CASCADE,
    is_primary          boolean NOT NULL DEFAULT false,
    position            integer NOT NULL DEFAULT 0,
    UNIQUE (product_id, category_id)
);

CREATE INDEX idx_product_category_category ON product_category (category_id);

-- ============================================================================
-- 3. Attributes (specs, variant axes and priced choices are the same thing)
-- ============================================================================

-- Attribute groups per product: the site's own sections ("Specifications",
-- a Magento attribute set, ...). name '' is the root group - its attributes
-- render ungrouped. Groups carry their own sort_order, independent of the
-- attributes inside them.
CREATE TABLE product_attribute_group (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    name                text NOT NULL DEFAULT '',
    sort_order          integer NOT NULL DEFAULT 0,
    UNIQUE (product_id, name)
);

-- "Material", "Size", "Spice level", "Extras". min_select/max_select are NULL
-- for informational attributes; set them when the page presents a choice.
-- An attribute whose values are linked from product_variant_value is a variant
-- axis: the variant carries the price, so its values' price_delta is ignored.
CREATE TABLE product_attribute (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    group_id            integer NOT NULL REFERENCES product_attribute_group(id) ON DELETE CASCADE,
    name                text NOT NULL,
    min_select          integer CHECK (min_select >= 0),
    max_select          integer CHECK (max_select >= 1),
    allow_quantity      boolean NOT NULL DEFAULT false, -- a value may be chosen several times; min/max count units
    sort_order          integer NOT NULL DEFAULT 0,
    UNIQUE (product_id, group_id, name),
    CHECK (max_select IS NULL OR min_select IS NULL OR max_select >= min_select)
);

-- "Leather", "Spicy" (+1.50)
CREATE TABLE product_attribute_value (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id        integer NOT NULL REFERENCES product_attribute(id) ON DELETE CASCADE,
    value               text NOT NULL,
    price_delta         numeric(19,4),                   -- signed; NULL = page shows no surcharge
    is_default          boolean NOT NULL DEFAULT false,
    is_available        boolean,                         -- NULL = unknown
    sort_order          integer NOT NULL DEFAULT 0,
    UNIQUE (attribute_id, value)
);

-- ============================================================================
-- 4. Variants and prices
-- ============================================================================

-- A combination with its own sku / price / stock. Prices are in site.currency.
-- Final price = variant price + sum(price_delta) of the selected values of
-- attributes that are not variant axes.
-- A variant whose last_seen_at is older than its product's was not on the
-- product's latest page.
CREATE TABLE product_variant (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,

    code                text NOT NULL DEFAULT '',        -- '' = default variant
    sort_order          integer NOT NULL DEFAULT 0,      -- the site's order of the product's variants
    name                text,
    sku                 text,
    gtin                text,                            -- UPC / EAN / ISBN
    mpn                 text,

    price               numeric(19,4),
    compare_at_price    numeric(19,4),                   -- "was" price
    price_type          text NOT NULL DEFAULT 'regular', -- regular, sale, member...
    sale_ends_at        timestamptz,
    unit_price          numeric(19,4),                   -- e.g. price per m2 / kg
    unit                text,

    availability        text                             -- NULL = unknown
                        CHECK (availability IN ('in_stock', 'out_of_stock', 'limited',
                                                'preorder', 'backorder', 'discontinued')),
    stock_qty           integer,

    weight              numeric(14,4),
    weight_unit         text,
    length              numeric(14,4),
    width               numeric(14,4),
    height              numeric(14,4),
    dimension_unit      text,

    last_seen_at        timestamptz NOT NULL DEFAULT now(),

    UNIQUE (product_id, code)
);

CREATE INDEX idx_product_variant_gtin ON product_variant (gtin) WHERE gtin IS NOT NULL;

-- Axis values that define a variant (Size: 10, Colour: Black); at most one
-- value per attribute, enforced by the crawler.
CREATE TABLE product_variant_value (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id          integer NOT NULL REFERENCES product_variant(id) ON DELETE CASCADE,
    attribute_value_id  integer NOT NULL REFERENCES product_attribute_value(id) ON DELETE CASCADE,
    UNIQUE (variant_id, attribute_value_id)
);

-- Price observations over time, with the fetch they came from.
CREATE TABLE variant_price (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id          integer NOT NULL REFERENCES product_variant(id) ON DELETE CASCADE,
    url_fetch_id        bigint REFERENCES url_fetch(id) ON DELETE SET NULL,
    observed_at         timestamptz NOT NULL,
    currency            char(3),                         -- site.currency at the time
    price               numeric(19,4),
    compare_at_price    numeric(19,4),
    price_type          text NOT NULL DEFAULT 'regular',
    sale_ends_at        timestamptz,
    unit_price          numeric(19,4),
    unit                text,
    availability        text,
    UNIQUE (variant_id, observed_at)
);

-- ============================================================================
-- 5. Media and assets
-- ============================================================================

CREATE TABLE product_image (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    url_id              bigint NOT NULL REFERENCES url(id) ON DELETE CASCADE,
    role                text NOT NULL DEFAULT 'gallery', -- gallery, thumbnail, swatch, large...
    position            integer NOT NULL DEFAULT 0,
    -- The product alone (a tile's face, a sofa on a plain backdrop), as opposed
    -- to a room scene, props or a graphic; null when the crawler cannot tell.
    pure                boolean,
    UNIQUE (product_id, url_id, role)
);

-- Variants an image shows; an image with no rows applies to the whole product.
CREATE TABLE product_image_variant (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id            integer NOT NULL REFERENCES product_image(id) ON DELETE CASCADE,
    variant_id          integer NOT NULL REFERENCES product_variant(id) ON DELETE CASCADE,
    UNIQUE (image_id, variant_id)
);

-- Downloads and other keyed extras (spec sheets, install guides, videos).
CREATE TABLE product_asset (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          integer NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    kind                text NOT NULL,                   -- document, video, link...
    name                text NOT NULL,
    value               text NOT NULL,                   -- usually a URL
    UNIQUE (product_id, kind, name)
);
