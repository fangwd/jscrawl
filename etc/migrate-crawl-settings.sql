-- Upgrade existing databases for scheduled crawls, acceptance checks and
-- regression snapshots. Existing crawlers stay manual and unchecked until
-- their settings are explicitly populated.
ALTER TABLE crawler ADD COLUMN IF NOT EXISTS refresh_minutes integer
    CHECK (refresh_minutes > 0);

ALTER TABLE site ADD COLUMN IF NOT EXISTS expect jsonb;

CREATE TABLE IF NOT EXISTS crawl_snapshot (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             integer NOT NULL REFERENCES site(id) ON DELETE CASCADE,
    taken_at            timestamptz NOT NULL DEFAULT now(),
    products            integer NOT NULL,
    fields              jsonb NOT NULL,
    pages               jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_crawl_snapshot_site ON crawl_snapshot (site_id, taken_at DESC);

-- A site refusing repeated fetches now ends a run as blocked. Keep earlier
-- run history while allowing the supervisor to record that new outcome.
ALTER TABLE crawler_run DROP CONSTRAINT IF EXISTS crawler_run_status_check;
ALTER TABLE crawler_run ADD CONSTRAINT crawler_run_status_check
    CHECK (status IN ('running', 'stopped', 'blocked', 'crashed', 'interrupted'));
